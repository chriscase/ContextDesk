#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum RaRole {
    Trigger,
    Propagation,
    Symptom,
    Recovery,
    Decoy,
    Neutral,
}

impl RaRole {
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Trigger => "trigger",
            Self::Propagation => "propagation",
            Self::Symptom => "symptom",
            Self::Recovery => "recovery",
            Self::Decoy => "decoy",
            Self::Neutral => "neutral",
        }
    }

    /// Default nDCG gain for a role. Truth may override per query.
    pub fn default_gain(self) -> u8 {
        match self {
            Self::Trigger => 3,
            Self::Propagation => 2,
            Self::Symptom | Self::Recovery | Self::Neutral => 1,
            Self::Decoy => 0,
        }
    }
}

/// The host-neutral ablation modes. A mode that cannot run in the current
/// build/environment MUST surface as `FUTURE_CAPABILITY_UNAVAILABLE` — never
/// silently substitute another mode and never count it as passing.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum RaMode {
    StructuredKeyword,
    HybridEmbedding,
    HybridEmbeddingReranked,
    FullMultistage,
}

impl RaMode {
    pub const ALL: [RaMode; 4] = [
        RaMode::StructuredKeyword,
        RaMode::HybridEmbedding,
        RaMode::HybridEmbeddingReranked,
        RaMode::FullMultistage,
    ];

    pub fn as_str(self) -> &'static str {
        match self {
            Self::StructuredKeyword => "structured_keyword",
            Self::HybridEmbedding => "hybrid_embedding",
            Self::HybridEmbeddingReranked => "hybrid_embedding_reranked",
            Self::FullMultistage => "full_multistage",
        }
    }

    pub fn parse(value: &str) -> LabResult<Self> {
        match value {
            "structured_keyword" => Ok(Self::StructuredKeyword),
            "hybrid_embedding" => Ok(Self::HybridEmbedding),
            "hybrid_embedding_reranked" => Ok(Self::HybridEmbeddingReranked),
            "full_multistage" => Ok(Self::FullMultistage),
            other => Err(format!("unsupported retrieval-ablation mode: {other}").into()),
        }
    }
}

impl fmt::Display for RaMode {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.as_str())
    }
}

