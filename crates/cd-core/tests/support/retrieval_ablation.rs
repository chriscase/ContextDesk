#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RaTier {
    Small,
    Medium,
    Large,
}

impl RaTier {
    pub fn parse(value: &str) -> LabResult<Self> {
        match value {
            "small" => Ok(Self::Small),
            "medium" => Ok(Self::Medium),
            "large" => Ok(Self::Large),
            other => Err(format!("unsupported retrieval-ablation tier: {other}").into()),
        }
    }

    pub fn as_str(self) -> &'static str {
        match self {
            Self::Small => "small",
            Self::Medium => "medium",
            Self::Large => "large",
        }
    }

    pub fn noise_multiplier(self) -> u64 {
        match self {
            Self::Small => 1,
            Self::Medium => RA_MEDIUM_NOISE_MULTIPLIER,
            Self::Large => RA_LARGE_NOISE_MULTIPLIER,
        }
    }
}

impl fmt::Display for RaTier {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.as_str())
    }
}

// ---------------------------------------------------------------------------
// Deterministic RNG (neutral surface only)
// ---------------------------------------------------------------------------

/// SplitMix64: tiny, stable-forever PRNG implemented locally so determinism
/// never depends on an external crate's stream stability. It randomises the
/// NEUTRAL surface only (identifiers, epoch shift, filler values); semantic
/// structure is fixed by the case specifications.
#[derive(Debug, Clone)]
pub struct RaRng(u64);

impl RaRng {
    pub fn new(seed: u64) -> Self {
        Self(seed)
    }

    pub fn for_case(seed: u64, case_id: &str) -> Self {
        Self(seed ^ fnv1a64(case_id.as_bytes()))
    }

    pub fn next_u64(&mut self) -> u64 {
        self.0 = self.0.wrapping_add(0x9E37_79B9_7F4A_7C15);
        let mut z = self.0;
        z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
        z ^ (z >> 31)
    }

    pub fn next_range(&mut self, bound: u64) -> u64 {
        if bound == 0 {
            return 0;
        }
        self.next_u64() % bound
    }

    /// Eight lowercase hex characters; the workhorse for request/trace ids.
    pub fn hex8(&mut self) -> String {
        format!("{:08x}", self.next_u64() & 0xFFFF_FFFF)
    }

    /// Eight UPPERCASE hex characters. Evidence-group tokens use this so a
    /// token can never collide with (or contain) a lowercase noise id; the
    /// production search is case-insensitive, while scorer token matching is
    /// deliberately case-sensitive.
    pub fn hex8_upper(&mut self) -> String {
        format!("{:08X}", self.next_u64() & 0xFFFF_FFFF)
    }
}

pub fn fnv1a64(bytes: &[u8]) -> u64 {
    let mut hash: u64 = 0xCBF2_9CE4_8422_2325;
    for byte in bytes {
        hash ^= u64::from(*byte);
        hash = hash.wrapping_mul(0x0000_0100_0000_01B3);
    }
    hash
}

/// Suite epoch for a seed: `RA_BASE_TS` plus a minute-quantised jitter in
/// `[-RA_SEED_JITTER_BOUND_SECS, +RA_SEED_JITTER_BOUND_SECS]`.
pub fn ra_suite_epoch(seed: u64) -> i64 {
    let mut rng = RaRng::new(seed ^ 0x5245_5452_4945_5641);
    let window = (RA_SEED_JITTER_BOUND_SECS * 2 / 60) as u64 + 1;
    let offset_minutes = rng.next_range(window) as i64;
    RA_BASE_TS - RA_SEED_JITTER_BOUND_SECS + offset_minutes * 60
}

