/// Canonical seed-invariant projection of a truth manifest. Excludes every
/// neutral-surface field (tokens, absolute timestamps, hashes, byte sizes)
/// and keeps the semantic skeleton. Used to prove "different seed => same
/// semantic truth".
pub fn ra_semantic_projection(truth: &RaTruthManifest) -> Value {
    let groups: Vec<Value> = truth
        .evidence_groups
        .iter()
        .map(|group| {
            json!({
                "group_id": group.group_id,
                "sources": group.sources,
                "role": group.role.as_str(),
                "incident_id": group.incident_id,
                "expected_token_records": group.expected_token_records,
                "expected_raw_records": group.expected_raw_records,
                "expected_occurrences": group.expected_occurrences,
                "timestamp_certainty": group.timestamp_certainty,
                "ts_rel": group.ts - truth.base_ts,
            })
        })
        .collect();
    let incidents: Vec<Value> = truth
        .incidents
        .iter()
        .map(|incident| {
            json!({
                "incident_id": incident.incident_id,
                "root_cause_status": incident.root_cause_status,
                "trigger_group_ids": incident.trigger_group_ids,
                "window_from_rel": incident.window_from_ts - truth.base_ts,
                "window_to_rel": incident.window_to_ts - truth.base_ts,
            })
        })
        .collect();
    let relevance: BTreeMap<&String, Value> = truth
        .per_query_relevance
        .iter()
        .map(|(query_id, entry)| {
            (
                query_id,
                json!({
                    "answerable": entry.answerable,
                    "relevant": entry.relevant.iter().map(|r| json!({
                        "group_id": r.group_id,
                        "gain": r.gain,
                    })).collect::<Vec<_>>(),
                    "contaminating_groups": entry.contaminating_groups,
                }),
            )
        })
        .collect();
    json!({
        "schema_id": truth.schema_id,
        "schema_version": truth.schema_version,
        "suite_id": truth.suite_id,
        "case_id": truth.case_id,
        "case_version": truth.case_version,
        "tier": truth.tier,
        "intended_probe": truth.intended_probe,
        "expected_events": truth.expected.events,
        "expected_sources": truth.expected.sources,
        "expected_severities": truth.expected.severities,
        "time_quality": truth.expected.time_quality,
        "excluded_files": truth.expected.excluded_files,
        "incidents": incidents,
        "evidence_groups": groups,
        "known_counts": {
            "corpus_completeness": truth.known_counts.corpus_completeness,
            "total_events_known": truth.known_counts.total_events_known,
            "known_missing_references": truth.known_counts.known_missing_references,
        },
        "required_claims": truth.required_claims,
        "forbidden_claims": truth.forbidden_claims,
        "competing_explanations": truth.competing_explanations,
        "permitted_uncertainty": truth.permitted_uncertainty,
        "secret_token_count": truth.privacy.secret_tokens.len(),
        "retrieval_exclusion_count": truth.retrieval_exclusions.len(),
        "per_query_relevance": relevance,
        "baseline_expectation": {
            "class": truth.baseline_expectation.class,
            "queries_expected_below_floor":
                truth.baseline_expectation.gates.queries_expected_below_floor,
        },
    })
}

pub fn ra_semantic_truth_digest(truth: &RaTruthManifest) -> LabResult<String> {
    let projection = ra_semantic_projection(truth);
    Ok(super::sha256_bytes(&serde_json::to_vec(&projection)?))
}

