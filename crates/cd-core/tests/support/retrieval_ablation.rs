//! Retrieval-ablation benchmark lab: deterministic hidden-truth corpus
//! generation, host-neutral mode contract, and versioned manifests.
//!
//! Included as a child of `log_lab_generator.rs` (exactly like
//! `log_lab_behavior.rs`) so it reuses the frozen Log Lab helpers
//! (`verify_safety`, `tree_hashes`, `json_line`, `logfmt`, deterministic ZIP)
//! instead of creating a parallel fixture system.
//!
//! Committed layout under `fixtures/log-lab/`:
//!
//! ```text
//! schema/retrieval-*.v1.schema.json          versioned contract documents
//! scenarios/retrieval-ablation/suite.json    suite manifest
//! scenarios/retrieval-ablation/cases/<id>/
//!     import/       model-visible logs (the ONLY import root)
//!     queries.json  harness input (model-safe questions + keyword plans)
//!     truth/        evaluator-only manifest (never import, never attach)
//! ```
//!
//! Evaluator truth references model-visible events by unique opaque message
//! token resolved to `(seq, source)` at scoring time — the same convention as
//! `fixtures/triage-root-cause-lab/`. Truth-only identifiers (`group_id`,
//! roles, gains) never appear under `import/`; isolation tests enforce this.

